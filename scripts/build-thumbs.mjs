// Turns a folder of thumbnail images into the optimized files the site uses.
//
//   npm run thumbs                 -> reads images from the parent folder (..)
//   npm run thumbs -- "C:/my/imgs" -> reads images from any folder
//
// For every image it writes public/thumbs/tNN.webp (960x540) and
// public/thumbs/tNN-sm.webp (480x270), and updates src/lib/thumb-count.ts so
// the site knows how many there are. Old files in public/thumbs are removed,
// so deleting an image from the source folder and re-running removes it from
// the site.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const source = path.resolve(process.argv[2] ?? path.join(root, ".."));
const out = path.join(root, "public", "thumbs");

const isImage = (f) => /\.(png|jpe?g|webp)$/i.test(f);
const files = fs
  .readdirSync(source)
  .filter((f) => isImage(f) && fs.statSync(path.join(source, f)).isFile())
  .sort();

if (files.length === 0) {
  console.error(`No images found in ${source}`);
  process.exit(1);
}

// Alternate high-res and low-res sources so neither clumps together in a row.
const big = [];
const small = [];
for (const f of files) {
  const { width = 0 } = await sharp(path.join(source, f)).metadata();
  (width >= 1200 ? big : small).push(f);
}
const order = [];
for (let i = 0; i < Math.max(big.length, small.length); i++) {
  if (big[i]) order.push(big[i]);
  if (small[i]) order.push(small[i]);
}

fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(out)) {
  if (f.endsWith(".webp")) fs.rmSync(path.join(out, f));
}

for (const [i, f] of order.entries()) {
  const id = `t${String(i + 1).padStart(2, "0")}`;
  const src = path.join(source, f);
  await sharp(src)
    .resize(960, 540, { fit: "cover" })
    .webp({ quality: 80, effort: 5 })
    .toFile(path.join(out, `${id}.webp`));
  await sharp(src)
    .resize(480, 270, { fit: "cover" })
    .webp({ quality: 78, effort: 5 })
    .toFile(path.join(out, `${id}-sm.webp`));
}

fs.writeFileSync(
  path.join(root, "src", "lib", "thumb-count.ts"),
  `// Generated by scripts/build-thumbs.mjs — number of thumbnails in /public/thumbs.\nexport const THUMB_COUNT = ${order.length};\n`,
);
console.log(`${order.length} thumbnails written to public/thumbs`);
